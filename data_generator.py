# =========================================================================
# Каждая запись в CATEGORY -> list соответствует ОДНОЙ фиксированной цели
# (target) с ОДНИМ набором переменных (given_gen), но НЕСКОЛЬКИМИ
# перефразировками текста ("texts") — при генерации формулировка
# выбирается случайно из списка. Это и есть лечение главной проблемы,
# найденной на реальных прогонах: модели, обученные на 1-3 фразах на тему,
# не обобщаются на живые перефразировки ("маятника" вместо "маятник",
# другой порядок слов и т.д.).
#
# В некоторых формулировках специально добавлены "ловушки" — посторонние
# числа с чужими единицами измерения рядом с нужными (год выпуска прибора,
# номер эксперимента, температура воздуха в комнате) — чтобы extractor не
# мог просто брать "любое число поблизости", а учился действительно
# понимать, какое число что означает.
#
# Значение target в тексте не фигурирует НИКОГДА — иначе получится
# "найди то, что уже написано в условии".

def _generate_collision_variants():
    """
    Автоматически генерирует несколько формулировок задачи о неупругом
    столкновении, комбинируя разные структуры предложения с ПРАВИЛЬНО
    СОГЛАСОВАННЫМИ падежными формами "покоящееся тело" под нужный предлог
    (с покоящимся [твор.] / на покоящееся [вин.] / в покоящееся [вин.]) —
    вместо того, чтобы вручную печатать и подбирать каждую словоформу.

    Это и есть масштабируемая альтернатива ручному перебору: чтобы
    добавить ещё структуру предложения, достаточно дописать (skeleton, case)
    в список ниже — согласование "прилагательное+существительное" в нужном
    падеже берёт на себя pymorphy3 (см. morphology.py), не нужно печатать
    словоформу руками и рисковать ошибиться с падежом/родом/числом.
    """
    openers = [
        ("Тело массой {{m1}} кг, движущееся со скоростью {{v1}} м/с, "
         "сталкивается неупруго с {rt} массой {{m2}} кг.", ABLT),
        ("Тело массой {{m1}} кг налетает со скоростью {{v1}} м/с на {rt} массой {{m2}} кг.", ACCS),
        ("Со скоростью {{v1}} м/с летит тело массой {{m1}} кг и врезается в {rt} массой {{m2}} кг.", ACCS),
        ("Двигаясь со скоростью {{v1}} м/с, тело массой {{m1}} кг сталкивается неупруго "
         "с {rt} массой {{m2}} кг.", ABLT),
    ]
    endings = [
        " Найдите ⟦скорость тел⟧ после столкновения.",
        " Определите ⟦итоговую скорость⟧.",
        " Вычислите ⟦скорость⟧ после столкновения.",
        " Какова будет ⟦скорость⟧ после удара?",
    ]
    variants = []
    for i, (skeleton, case) in enumerate(openers):
        resting_thing = decline_phrase(["покоящееся", "тело"], case)
        variants.append(skeleton.format(rt=resting_thing) + endings[i % len(endings)])
    return variants


