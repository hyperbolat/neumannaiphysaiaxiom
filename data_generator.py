def rnd(lo, hi, digits=2):
    return round(random.uniform(lo, hi), digits)


# =========================================================================
# ВЫРАВНИВАНИЕ ДЛЯ ИЗВЛЕЧЕНИЯ СУЩНОСТЕЙ (этап 4)
# =========================================================================
# Placeholder {var} рендерится в текст с точным отслеживанием позиции
# символов, куда попало число — это даёт возможность потом разметить
# каждый токен меткой "какой переменной он соответствует" (или "O", если
# токен не является значением переменной). Числа в нашей схеме — всегда
# один токен (см. TOKEN_RE), поэтому BIO-теги не нужны: разметка "плоская"
# (O или имя переменной), без Begin/Inside.

PLACEHOLDER_RE = re.compile(r'\{(\w+)\}')
TOKEN_RE = re.compile(r'\d+\.?\d*(?:[eE][-+]?\d+)?|[a-zA-Zа-яА-ЯёЁ]+')

# ⟦...⟧ размечает в тексте шаблона СЛОВО/ФРАЗУ, называющую искомую величину
# ("Найдите ⟦ускорение⟧тела." -> "Найдите ускорение тела.", а "ускорение"
# получает метку той же переменной, что и target шаблона). Это даёт
# extractor'у возможность узнавать не только "какое число — какая
# переменная" (по числовым токенам), но и "что вообще ищем" (по словесному
# токену) — той же моделью, тем же набором меток, без новой архитектуры.
TARGET_MARK_RE = re.compile(r'⟦(.*?)⟧')
COMBINED_RE = re.compile(r'\{(\w+)\}|⟦(.*?)⟧')


def render_with_spans(template: str, values: dict, target_var: str = None):
    """
    Рендерит шаблон в текст, попутно вычисляя:
      - spans[var] = (start, end) для каждой ЧИСЛОВОЙ переменной из {var},
      - spans[target_var] = (start, end) для словесной фразы из ⟦...⟧,
        если target_var передан и маркер есть в шаблоне.
    Оба вида разметки обрабатываются в ОДНОМ проходе по символам, чтобы
    смещения не разъезжались при замене плейсхолдеров на числа разной длины.
    """
    result = []
    spans = {}
    pos = 0
    last_end = 0
    for m in COMBINED_RE.finditer(template):
        chunk = template[last_end:m.start()]
        result.append(chunk)
        pos += len(chunk)

        if m.group(1) is not None:
            # {var} — числовое значение
            var = m.group(1)
            val_str = str(values[var])
            start = pos
            result.append(val_str)
            pos += len(val_str)
            spans[var] = (start, pos)
        else:
            # ⟦фраза⟧ — словесное упоминание искомой величины
            phrase = m.group(2)
            start = pos
            result.append(phrase)
            pos += len(phrase)
            if target_var is not None:
                spans[target_var] = (start, pos)

        last_end = m.end()
    result.append(template[last_end:])
    return ''.join(result), spans


def label_tokens(text: str, spans: dict):
    """Токенизирует текст и присваивает каждому токену метку переменной или 'O'."""
    tokens, labels = [], []
    for m in TOKEN_RE.finditer(text):
        tok, (s, e) = m.group(), m.span()
        label = "O"
        for var, (vs, ve) in spans.items():
            if s >= vs and e <= ve:
                label = var
                break
        tokens.append(tok)
        labels.append(label)
    return tokens, labels


