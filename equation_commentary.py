for _eq, _name, _text in _TABLE:
    key = _base_symbol_set(_eq)
    # При коллизии (несколько уравнений с одинаковым базовым набором символов)
    # оставляем первое — это осознанный компромисс для редких клонированных
    # случаев; точный индекс (EXACT_INDEX) покрывает подавляющее большинство
    # уравнений и не подвержен этой неоднозначности.
    if key not in BASE_INDEX:
        BASE_INDEX[key] = (_name, _text)
