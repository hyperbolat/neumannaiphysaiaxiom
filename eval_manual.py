def run_eval():
    from parserx import PyTorchParser
    from extractor import PyTorchExtractor
    from solver import PhysicsSolver

    parser = PyTorchParser()
    extractor = PyTorchExtractor()
    solver = PhysicsSolver()

    n = len(EVAL_SET)
    cat_correct = 0
    extraction_exact = 0
    var_tp, var_fp, var_fn = 0, 0, 0
    solved_end_to_end = 0

    print(f"\n{'='*90}\nEVAL: {n} рукописных примеров\n{'='*90}\n")

    for i, ex in enumerate(EVAL_SET, 1):
        pred_cat = parser.predict_category(ex["text"])
        pred_given = extractor.extract(ex["text"])

        cat_ok = pred_cat == ex["category"]
        cat_correct += cat_ok

        expected_keys = set(ex["given"].keys())
        pred_keys = set(pred_given.keys())
        var_tp += len(expected_keys & pred_keys)
        var_fp += len(pred_keys - expected_keys)
        var_fn += len(expected_keys - pred_keys)

        exact = all(
            k in pred_given and abs(pred_given[k] - v) < 1e-6 * max(abs(v), 1)
            for k, v in ex["given"].items()
        ) and len(pred_given) == len(ex["given"])
        extraction_exact += exact

        # end-to-end: используем ПРЕДСКАЗАННЫЕ категорию и данные (не эталонные!)
        # Таймаут обязателен: если extractor выдал "мусорные" данные (перепутанные
        # переменные, дикие порядки величин), система уравнений иногда уходит в
        # патологический случай, на котором sp.solve может зависнуть на очень
        # долго — один плохой пример не должен вешать весь прогон эвала.
        class _EvalTimeout(Exception):
            pass

        def _on_timeout(signum, frame):
            raise _EvalTimeout()

        old_handler = signal.signal(signal.SIGALRM, _on_timeout)
        signal.alarm(8)
        try:
            result, _ = solver.calculate(dict(pred_given), ex["target"], pred_cat, ex["text"])
            solved = isinstance(result, (int, float))
        except _EvalTimeout:
            solved = False
            result = "TIMEOUT (>8s)"
        except Exception:
            solved = False
        finally:
            signal.alarm(0)
            signal.signal(signal.SIGALRM, old_handler)
        solved_end_to_end += solved

        status = "OK " if (cat_ok and exact and solved) else "..."
        print(f"[{status}] #{i:2d} cat={'OK' if cat_ok else 'FAIL':4s} "
              f"extract={'OK' if exact else 'FAIL':4s} solve={'OK' if solved else 'FAIL':4s}  "
              f"{ex['text'][:60]}...")
        if not cat_ok:
            print(f"        категория: ожидали '{ex['category']}', получили '{pred_cat}'")
        if not exact:
            print(f"        данные: ожидали {ex['given']}, получили {pred_given}")

    precision = var_tp / max(var_tp + var_fp, 1)
    recall = var_tp / max(var_tp + var_fn, 1)
    f1 = 2 * precision * recall / max(precision + recall, 1e-9)

    print(f"\n{'='*90}")
    print(f"Классификация:       {cat_correct}/{n}  ({100*cat_correct/n:.1f}%)")
    print(f"Извлечение (точное): {extraction_exact}/{n}  ({100*extraction_exact/n:.1f}%)")
    print(f"Извлечение per-var:  precision={precision:.3f}  recall={recall:.3f}  f1={f1:.3f}")
    print(f"End-to-end решено:   {solved_end_to_end}/{n}  ({100*solved_end_to_end/n:.1f}%)")
    print(f"{'='*90}\n")


if __name__ == "__main__":
    run_eval()