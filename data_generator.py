"""
Генератор синтетических физических задач для обучающего корпуса.

Идея: вместо того чтобы копировать формулировки из задачника (что нельзя
по копирайту и не даёт достаточно данных), мы генерируем собственные
русскоязычные перефразировки на основе физических шаблонов, привязанных
к системе уравнений в physics_db.EQUATIONS. Для каждого шаблона:
  - случайно подставляются физически правдоподобные числа для ДАННЫХ величин,
  - искомая величина у каждой формулировки фиксирована и НИКОГДА не
    подставляется в текст как число (иначе получится "найди то, что уже
    написано в условии" — бессмысленный пример для обучения).

Это даёт неограниченный (в разумных пределах) набор размеченных пар
(текст → категория, набор переменных, цель) без каких-либо копирайтных
рисков — сама формула не защищена авторским правом, а наши формулировки
условия — целиком собственные.

Использование:
    python3 data_generator.py --per-template 30 --out dataset.jsonl
"""

