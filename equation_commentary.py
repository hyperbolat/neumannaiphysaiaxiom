# Индекс для совпадения по "базовому" набору символов без цифровых индексов
# (нужен для уравнений, которые solver.py клонирует под многотельные задачи:
# кинематика и "Динамика (одно тело)" — единственные категории, чьи символы
# входят в список клонируемых в solver.py).
import re as _re


def _base_symbol_set(eq):
    names = set()
    for sym in eq.free_symbols:
        names.add(_re.sub(r'\d+$', '', sym.name))
    return frozenset(names)


