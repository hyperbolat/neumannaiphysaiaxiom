def generate_dataset(per_template: int, seed: int = 42):
    random.seed(seed)
    dataset = []
    for category, templates in TEMPLATES.items():
        for tmpl in templates:
            for _ in range(per_template):
                given = tmpl["given_gen"]()
                text_template = random.choice(tmpl["texts"])
                text, spans = render_with_spans(text_template, given, target_var=tmpl["target"])
                # "seed_num"/"trap_year" — чисто декоративные ловушки (номер стенда/
                # баллона/эксперимента, диаметр нити, год опыта), не физические
                # величины. Убираем их из spans ДО разметки токенов, чтобы они
                # честно получили метку "O", а не притворялись настоящей
                # переменной с собственным классом.
                TRAP_VARS = ("seed_num", "trap_year")
                for trap_var in TRAP_VARS:
                    spans.pop(trap_var, None)
                tokens, labels = label_tokens(text, spans)
                given_clean = {k: v for k, v in given.items() if k not in TRAP_VARS}
                dataset.append({
                    "text": text,
                    "category": category,
                    "given": given_clean,
                    "target": tmpl["target"],
                    "tokens": tokens,
                    "labels": labels,
                    # Посимвольные спаны {var: [start, end]} — нужны для выравнивания
                    # с subword-токенизацией трансформера (у нас свой word-level
                    # TOKEN_RE, у BERT-токенизатора — свой BPE/WordPiece, они не
                    # совпадают токен-в-токен, поэтому выравниваем по символам).
                    "spans": {var: [s, e] for var, (s, e) in spans.items()},
                })
    random.shuffle(dataset)
    return dataset

def main():
    parser = argparse.ArgumentParser(description="Генератор синтетических физических задач")
    parser.add_argument("--per-template", type=int, default=30,
                         help="Сколько примеров генерировать на каждый шаблон")
    parser.add_argument("--out", type=str, default="dataset.jsonl")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    dataset = generate_dataset(args.per_template, args.seed)

    with open(args.out, "w", encoding="utf-8") as f:
        for row in dataset:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    categories = sorted(set(r["category"] for r in dataset))
    n_templates = sum(len(t) for t in TEMPLATES.values())
    print(f"Сгенерировано {len(dataset)} примеров, {len(categories)} категорий, {n_templates} шаблонов.")
    print(f"Сохранено в {args.out}")
    print("\nПримеры:")
    for row in dataset[:5]:
        print(f"  [{row['category']}] target={row['target']}")
        print(f"    {row['text']}")
        print(f"    дано: {row['given']}")


if __name__ == "__main__":
    main()